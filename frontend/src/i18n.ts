// Read a prompt aloud using the browser's built-in speech synthesis.
// Zero assets, works offline, and genuinely helps a child who reads little.
export function speak(text: string, lang: Lang) {
  if (typeof window === "undefined" || !("speechSynthesis" in window)) return;
  window.speechSynthesis.cancel();
  const u = new SpeechSynthesisUtterance(text);
  u.lang = lang === "ar" ? "ar-EG" : "en-US";
  u.rate = 0.9; // a touch slower, easier to follow
  window.speechSynthesis.speak(u);
}
